import java.util.Scanner;

public class Aula04 {
    static void main() {
        Scanner sc = new Scanner(System.in);
        System.out.println(7/2); // numeros inteiros (automaticamente ele modifica para inteiro)
        System.out.println(7 / 2.0); // numeros como hexadecimais (automaticamente ele mostra o numero quebrado)
        System.out.println(7.0 / 2); // numeros como hexadecimais (automaticamente ele mostra o numero quebrado)
        System.out.println(7 % 2); // mostra o resto da divisão
        System.out.println(1 / 2); // mostra a divisão como inteiro
    }
}
